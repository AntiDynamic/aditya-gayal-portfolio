import { chromium } from "playwright";
import { mkdir, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";

const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--enable-gpu", "--use-gl=angle", "--use-angle=gl"] });
const report = { checks: [], errors: [] };
const output = "visual-qa/room/selection";
await mkdir(output, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
  page.on("pageerror", error => report.errors.push(error.message));
  await page.goto(`${process.env.QA_URL || "http://localhost:3000"}/?room=1&motion=full`, { waitUntil: "networkidle" });
  await page.locator('[data-room][data-phase="ready"]').waitFor({ timeout: 60000 });
  await page.getByRole("button", { name: "Enter room", exact: true }).click();
  await page.waitForTimeout(300);
  await page.keyboard.press("Escape");
  await page.waitForTimeout(350);
  await page.locator('[data-room] details summary').click();
  await page.getByRole("navigation", { name: "Keyboard viewpoints" }).getByRole("button", { name: "shelf", exact: true }).click();
  await page.waitForTimeout(1500);
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), "shelf");
  await page.keyboard.press("e");
  await page.locator('[data-room][data-phase="inspect"]').waitFor({ timeout: 3000 });
  report.checks.push("E inspects after shelf selection without manually focusing canvas");
  await page.keyboard.press("e");
  await page.waitForTimeout(1000);
  assert.equal(await page.locator("[data-room]").getAttribute("data-phase"), "explore");
  report.checks.push("E returns once without immediately reopening inspection");
  assert.equal(await page.getByRole("button", { name: "Resume mouse look" }).evaluate(node => document.activeElement === node), true);
  const afterInspection = await page.locator("[data-room]").getAttribute("data-camera");
  await page.keyboard.down("s"); await page.waitForTimeout(450); await page.keyboard.up("s");
  await page.waitForTimeout(250);
  assert.notEqual(await page.locator("[data-room]").getAttribute("data-camera"), afterInspection);
  report.checks.push("WASD moves after returning from inspection with Resume button focused");
  await page.locator('[data-room] details summary').click();
  await page.getByRole("navigation", { name: "Keyboard viewpoints" }).getByRole("button", { name: "desk", exact: true }).click();
  await page.waitForTimeout(1400);
  const before = await page.locator("[data-room]").getAttribute("data-camera");
  await page.keyboard.down("s"); await page.waitForTimeout(450); await page.keyboard.up("s");
  await page.waitForTimeout(250);
  assert.notEqual(await page.locator("[data-room]").getAttribute("data-camera"), before);
  report.checks.push("WASD moves after viewpoint selection with button focus");
  await page.getByRole("button", { name: "Resume mouse look" }).click();
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.pointerLockElement !== null), true);
  await page.keyboard.press("Escape");
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.pointerLockElement !== null), false);
  report.checks.push("Pointer lock resumes and Escape releases after selection");
  await page.locator('[data-room] details summary').click();
  await page.getByRole("navigation", { name: "Keyboard viewpoints" }).getByRole("button", { name: "notebook", exact: true }).click();
  await page.waitForTimeout(1400);
  await page.mouse.move(683, 384); await page.mouse.down(); await page.mouse.move(689, 384, { steps: 4 }); await page.mouse.up();
  await page.waitForTimeout(150);
  assert.equal(await page.locator("[data-room]").getAttribute("data-phase"), "explore");
  report.checks.push("Drag look does not accidentally open inspection");
  await page.mouse.click(689, 384);
  await page.locator('[data-room][data-phase="inspect"]').waitFor();
  await page.getByRole("button", { name: "Back", exact: false }).click();
  await page.waitForTimeout(1000);
  assert.equal(await page.locator("[data-room]").getAttribute("data-phase"), "explore");
  report.checks.push("A deliberate click still inspects after drag look");
  await page.screenshot({ path: `${output}/recovered-controls.png` });
  assert.equal(report.errors.length, 0);
} catch (error) { report.failure = error.stack; process.exitCode = 1; }
finally { await browser.close(); await writeFile(`${output}/report.json`, JSON.stringify(report, null, 2)); console.log(report); }
